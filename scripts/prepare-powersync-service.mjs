#!/usr/bin/env node
/**
 * Generates the PowerSync service config used by the local Docker stack.
 *
 *   bun run sync:up   (runs this first)
 *
 * Why: the Service normally fetches our JWKS over HTTP (`client_auth.jwks_uri`).
 * On developer machines and hardened hosts the container is often not allowed to
 * reach a process on the host, which would break every local sync with a 401.
 * The Service supports inline keys *in addition to* a JWKS URI, so for local
 * development we inline the API's current public JWK into
 * `powersync/.generated/service.yaml` (gitignored).
 *
 * Production and CI keep using the committed `powersync/service.yaml` with the
 * real `jwks_uri`, so key rotation needs no redeploy.
 *
 * Run with a stable `POS_JWT_PRIVATE_KEY` in `.env`, otherwise the API's
 * ephemeral key changes on every restart and this file must be regenerated.
 *
 * The container must be recreated after this writes, not just started: a
 * running PowerSync process keeps the config it booted with. `bun run sync:up`
 * passes `--force-recreate` for exactly that reason.
 */
import fs from 'node:fs'
import path from 'node:path'
import YAML from 'yaml'

const root = path.resolve(import.meta.dirname, '..')
const servicePath = path.join(root, 'powersync', 'service.yaml')
const outputDir = path.join(root, 'powersync', '.generated')
const outputPath = path.join(outputDir, 'service.yaml')
const apiBaseUrl = process.env.API_BASE_URL ?? 'http://localhost:4000'

// Identity: keep the scalar text and let the tag marker be re-emitted on output.
const envTag = { tag: '!env', resolve: (value) => value }

const raw = fs.readFileSync(servicePath, 'utf8')
// `parseDocument` keeps the `!env` tags, so stringifying still emits them.
const doc = YAML.parseDocument(raw, { customTags: [envTag] })

function write(note) {
  fs.mkdirSync(outputDir, { recursive: true })
  fs.writeFileSync(
    outputPath,
    [
      '# GENERATED by scripts/prepare-powersync-service.mjs — do not edit.',
      `# ${note}`,
      doc.toString().trimEnd(),
      '',
    ].join('\n'),
  )
  console.log(`[sync] wrote ${path.relative(root, outputPath)} (${note})`)
}

async function fetchJwks() {
  const response = await fetch(`${apiBaseUrl}/.well-known/jwks.json`, {
    signal: AbortSignal.timeout(3000),
  })
  if (!response.ok) throw new Error(`JWKS endpoint returned ${response.status}`)
  const body = await response.json()
  if (!Array.isArray(body?.keys) || body.keys.length === 0) {
    throw new Error('JWKS response has no keys')
  }
  return body
}

try {
  const jwks = await fetchJwks()
  const audience = doc.getIn(['client_auth', 'audience'])
  // Inline the public key and drop the URI, so an unreachable host cannot break
  // sync. `audience` is carried over verbatim.
  doc.setIn(['client_auth'], { audience: audience ?? ['http://localhost:8080'], jwks })
  write(`client_auth inlined from ${apiBaseUrl}/.well-known/jwks.json`)
} catch (error) {
  const reason = error instanceof Error ? error.message : String(error)
  console.warn(`[sync] could not read the API JWKS (${reason}); falling back to jwks_uri`)
  console.warn('[sync] the PowerSync container must then be able to reach the API on the host')
  write('verbatim copy of service.yaml (JWKS fetched over HTTP)')
}
