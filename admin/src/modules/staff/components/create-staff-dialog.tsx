import type { Role } from "@sceptre/shared"
import { useMutation, useQueryClient } from "@tanstack/react-query"
import { type FormEvent, useEffect, useState } from "react"
import { Button } from "#/components/ui/button"
import {
	Dialog,
	DialogContent,
	DialogDescription,
	DialogFooter,
	DialogHeader,
	DialogTitle,
} from "#/components/ui/dialog"
import { Input } from "#/components/ui/input"
import { Label } from "#/components/ui/label"
import {
	Select,
	SelectContent,
	SelectItem,
	SelectTrigger,
	SelectValue,
} from "#/components/ui/select"
import type { Session } from "#/lib/auth-client"
import { useBranch } from "#/lib/branch-context"
import { toastApiError } from "#/lib/toast"
import { staffKeys } from "../api/keys"
import { createStaff } from "../api/staff"
import type { CreateStaffResult, Staff } from "../types"

/**
 * Create a console account. The temporary password is generated by the API and handed to the
 * caller's `onCreated`, which is what shows the one-time dialog.
 */
export function CreateStaffDialog({
	open,
	onOpenChange,
	onCreated,
	session,
}: {
	open: boolean
	onOpenChange: (open: boolean) => void
	onCreated: (result: { staff: Staff; temporaryPassword: string; invitationSent: boolean }) => void
	/** Passed in rather than read from the route: components do not reach into the route tree. */
	session: Session
}) {
	const queryClient = useQueryClient()
	const { branches, canSelectBranch } = useBranch()

	const isAdmin = session.user.role === "ADMIN"
	const roleOptions: Role[] = isAdmin ? ["ADMIN", "MANAGER", "CASHIER"] : ["MANAGER", "CASHIER"]

	const [email, setEmail] = useState("")
	const [name, setName] = useState("")
	const [role, setRole] = useState<Role>(roleOptions[0] ?? "CASHIER")
	const [branchId, setBranchId] = useState(session.user.branchId ?? "")
	const [phone, setPhone] = useState("")
	const [formError, setFormError] = useState<string | null>(null)

	useEffect(() => {
		if (!open) return
		setBranchId(session.user.branchId ?? "")
	}, [open, session.user.branchId])

	const needsBranch = role !== "ADMIN"

	const createMutation = useMutation({
		mutationFn: () =>
			createStaff({
				email,
				name,
				role,
				branchId: needsBranch ? branchId : null,
				phone: phone || undefined,
			}),
		onSuccess: async (data: CreateStaffResult) => {
			onOpenChange(false)
			reset()
			onCreated(data)
			await queryClient.invalidateQueries({ queryKey: staffKeys.all })
		},
		onError: (error) => {
			setFormError(null)
			toastApiError(error)
		},
	})

	function reset() {
		setEmail("")
		setName("")
		setRole(roleOptions[0] ?? "CASHIER")
		setPhone("")
		setFormError(null)
	}

	function handleSubmit(event: FormEvent<HTMLFormElement>) {
		event.preventDefault()
		if (needsBranch && !branchId) {
			setFormError("Choose a branch for this account.")
			return
		}
		createMutation.mutate()
	}

	return (
		<Dialog
			open={open}
			onOpenChange={(next) => {
				onOpenChange(next)
				if (!next) reset()
			}}
		>
			<DialogContent className="sm:max-w-sm">
				<DialogHeader>
					<DialogTitle>New staff account</DialogTitle>
					<DialogDescription>
						A temporary password is generated and the account must change it at first sign-in.
					</DialogDescription>
				</DialogHeader>

				<form onSubmit={handleSubmit} className="grid gap-4">
					<div className="grid gap-1.5">
						<Label htmlFor="staff-name">Name</Label>
						<Input
							id="staff-name"
							required
							minLength={2}
							value={name}
							onChange={(event) => setName(event.target.value)}
						/>
					</div>

					<div className="grid gap-1.5">
						<Label htmlFor="staff-email">Email</Label>
						<Input
							id="staff-email"
							type="email"
							required
							value={email}
							onChange={(event) => setEmail(event.target.value)}
						/>
					</div>

					<div className="grid grid-cols-2 gap-3">
						<div className="grid gap-1.5">
							<Label htmlFor="staff-role">Role</Label>
							<Select value={role} onValueChange={(value) => setRole(value as Role)}>
								<SelectTrigger id="staff-role" className="w-full">
									<SelectValue />
								</SelectTrigger>
								<SelectContent>
									{roleOptions.map((option) => (
										<SelectItem key={option} value={option}>
											{option === "ADMIN" ? "Admin" : option === "MANAGER" ? "Manager" : "Cashier"}
										</SelectItem>
									))}
								</SelectContent>
							</Select>
						</div>
						{needsBranch && canSelectBranch ? (
							<div className="grid gap-1.5">
								<Label htmlFor="staff-branch">Branch</Label>
								<Select value={branchId} onValueChange={setBranchId}>
									<SelectTrigger id="staff-branch" className="w-full">
										<SelectValue placeholder="Select" />
									</SelectTrigger>
									<SelectContent>
										{branches
											.filter((branch) => branch.isActive)
											.map((branch) => (
												<SelectItem key={branch.id} value={branch.id}>
													{branch.code}
												</SelectItem>
											))}
									</SelectContent>
								</Select>
							</div>
						) : null}
					</div>

					<div className="grid gap-1.5">
						<Label htmlFor="staff-phone">Phone</Label>
						<Input
							id="staff-phone"
							value={phone}
							onChange={(event) => setPhone(event.target.value)}
						/>
					</div>

					{formError ? (
						<p role="alert" className="text-sm text-destructive">
							{formError}
						</p>
					) : null}

					<DialogFooter>
						<Button type="button" variant="outline" onClick={() => onOpenChange(false)}>
							Cancel
						</Button>
						<Button type="submit" disabled={createMutation.isPending}>
							{createMutation.isPending ? "Creating…" : "Create account"}
						</Button>
					</DialogFooter>
				</form>
			</DialogContent>
		</Dialog>
	)
}
