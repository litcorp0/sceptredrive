import { formatDateTime } from "@sceptre/shared"
import { getRouteApi } from "@tanstack/react-router"
import { type ReactNode, useEffect, useState } from "react"

const authenticatedRoute = getRouteApi("/_authenticated")

export interface PrintSheetMeta {
	label: string
	value: string
}

interface PrintSheetProps {
	/** What the page is: "Stock report", "Credit aging as at 27 Oct 2026". */
	title: string
	/**
	 * The facts that make the page fileable: branch, period, as-of, filters. The generated
	 * time and the author are appended by this component, so no sheet can omit them.
	 */
	meta: PrintSheetMeta[]
	/** Report content to print inside the sheet. Omit when the screen itself prints in place. */
	children?: ReactNode
}

/**
 * The provenance block above every printed report (P14-D20).
 *
 * A printed page outlives the tab it came from: without a period, a branch and an as-of, the
 * number on it cannot be reconciled to anything, and the person who files it has no way to
 * find out later. So the sheet is deliberately not just a title — it names the branch, the
 * period, the instant the figures were read, when the page was generated and by whom. The
 * time and author are added here rather than by each page, because the one page that forgets
 * is the page that gets filed wrong.
 *
 * On screen it is `hidden`; `@media print` in `styles.css` shows it and hides the toolbar
 * that produced it. `data-print-meta` is the contract the walkthrough reads.
 */
export function PrintSheet({ title, meta, children }: PrintSheetProps) {
	const { session } = authenticatedRoute.useRouteContext()
	// Set after mount: a server-rendered clock would disagree with the client's on hydration.
	const [generatedAt, setGeneratedAt] = useState<Date | null>(null)
	useEffect(() => {
		setGeneratedAt(new Date())
	}, [])

	const author = session.user.staffId
		? `${session.user.name} (${session.user.staffId})`
		: session.user.name

	const rows: PrintSheetMeta[] = [
		...meta,
		{ label: "Generated", value: generatedAt ? formatDateTime(generatedAt) : "—" },
		{ label: "Generated by", value: author },
	]

	return (
		<section
			data-slot="print-sheet"
			data-print-sheet={title}
			className="mb-4 hidden border-b pb-3 print:block"
		>
			<h2 className="font-display text-lg">{title}</h2>
			<dl data-slot="print-meta" className="mt-2 grid grid-cols-2 gap-x-8 gap-y-1 text-xs">
				{rows.map((row) => (
					<div key={row.label} className="flex min-w-0 gap-2">
						<dt className="shrink-0 text-muted-foreground">{row.label}</dt>
						<dd className="min-w-0 font-medium break-words">{row.value}</dd>
					</div>
				))}
			</dl>
			{children ? <div className="mt-3">{children}</div> : null}
		</section>
	)
}
