import { Download } from "lucide-react"
import { useState } from "react"
import { toast } from "sonner"
import { Button } from "#/components/ui/button"
import { ApiError, apiDownload } from "#/lib/api"

interface ExportButtonProps {
	/** The API's CSV route for this read, e.g. `/api/credit/aging/export`. */
	path: string
	/** The same filters the table above is showing, so the file can never hold more. */
	query?: object
	/** Used in the toast and the accessible name: "Credit aging CSV". */
	label?: string
	/** Set while the report is still loading: half a report is worse than none. */
	disabled?: boolean
	/**
	 * Tooltip. Defaults to the money note because most reports carry `_minor` columns; a
	 * report with no money passes its own sentence.
	 */
	title?: string
	/**
	 * The id of the element that says why the button is disabled. A disabled button is
	 * still focusable-adjacent and its `title` is not always announced, so the reason a
	 * report cannot be exported belongs in an `aria-describedby` target.
	 */
	describedBy?: string
}

/**
 * The one export control in the console.
 *
 * The file is generated by the API (`apiDownload`) with the viewer's own filters, so the
 * export can never contain a row the table could not show, and the browser never assembles
 * a report. Money stays in integer minor units in the file; only the screen divides by 100,
 * and only through `formatGhs`.
 *
 * `data-export-path` is the tested contract: the walkthrough asserts the button on each
 * report screen points at that report's endpoint without driving a download.
 */
export function ExportButton({
	path,
	query = {},
	label = "Report",
	disabled,
	title = "Amounts are in pesewas",
	describedBy,
}: ExportButtonProps) {
	const [pending, setPending] = useState(false)

	async function download() {
		setPending(true)
		try {
			const { blob, filename } = await apiDownload(path, query)
			const url = URL.createObjectURL(blob)
			const anchor = document.createElement("a")
			anchor.href = url
			anchor.download = filename
			document.body.append(anchor)
			anchor.click()
			anchor.remove()
			URL.revokeObjectURL(url)
			toast.success(`${label} CSV downloaded`)
		} catch (error) {
			const message = error instanceof ApiError ? error.message : "The export failed."
			toast.error(`Could not export ${label.toLowerCase()}.`, { description: message })
		} finally {
			setPending(false)
		}
	}

	return (
		<Button
			type="button"
			variant="outline"
			size="sm"
			onClick={download}
			disabled={pending || disabled}
			title={title}
			aria-label={`Export ${label} CSV`}
			aria-describedby={describedBy}
			data-slot="export-button"
			data-export-path={path}
		>
			<Download aria-hidden="true" className="size-4" />
			{pending ? "Preparing…" : "Export CSV"}
		</Button>
	)
}
